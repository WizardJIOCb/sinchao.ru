function dish(
  id: string,
  categoryId: string,
  name: string,
  localizedName: string,
  description: string,
  price: number,
  portion: string,
  source: number,
  crop: [number, number, number, number],
  modifiers: ModifierGroup[] = [],
  featured = false,
): Dish {
  const [file, sourceWidth, sourceHeight] = sources[source];
  const [x, y, width, height] = crop;
  return extractedDishImage({
    id,
    categoryId,
    name,
    localizedName,
    description,
    ingredients: description
      .split(".")[0]
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean),
    price: price * 100,
    portion,
    image: "/images/vk-group/" + file + ".jpg",
    imageCrop: {
      x: x + 10,
      y: y + 10,
      width: width - 20,
      height: height - 20,
      sourceWidth,
      sourceHeight,
    },
    allergens: [],
    tags: [],
    spice: 0,
    available: true,
    featured,
    region: "",
    modifiers,
  });
}
