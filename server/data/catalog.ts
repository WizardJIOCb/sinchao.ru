const choice = (
  id: string,
  name: string,
  values: [string, string, number][],
): ModifierGroup => ({
  id,
  name,
  min: 1,
  max: 1,
  options: values.map(([id, name, price]) => ({
    id,
    name,
    price: price * 100,
    available: true,
  })),
});
